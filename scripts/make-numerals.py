"""One-off helper: turns the digits 0-9 of Fredoka SemiBold into SVG path data for the Little Animals cards.
The card export (html2canvas) cannot use web fonts inside SVG, so the big painted numbers are stored as outlines.
Needs fontTools (pip install fonttools) and Fredoka[wdth,wght].ttf from github.com/google/fonts (ofl/fredoka).
Usage: python3 scripts/make-numerals.py path/to/Fredoka[wdth,wght].ttf > src/assets/js/generators/milestones/numerals.js"""
import sys
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

font = instantiateVariableFont(TTFont(sys.argv[1]), {'wght': 600, 'wdth': 100})
gs, cmap, upm = font.getGlyphSet(), font.getBestCmap(), font['head'].unitsPerEm
out = {}
for ch in '0123456789':
    name = cmap[ord(ch)]
    pen = SVGPathPen(gs, ntos=lambda v: str(round(v)))
    gs[name].draw(TransformPen(pen, (1, 0, 0, -1, 0, 0)))          # flip y: SVG grows downwards
    out[ch] = (pen.getCommands(), gs[name].width)
print('/* Fredoka SemiBold digit outlines (SIL Open Font License), generated by scripts/make-numerals.py.')
print('   Units: 1000 per em, baseline at y=0, y grows downwards. */')
print(f'export const UPM = {upm};')
print('export const DIGITS = {')
for ch, (d, w) in out.items(): print(f"  '{ch}': {{ w: {w}, d: '{d}' }},")
print('};')
